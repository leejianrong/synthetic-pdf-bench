"""YOLO and Hugging Face imagefolder exports, derived from the COCO export so all three agree."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from synthetic_pdf_bench.export.coco import CATEGORIES, export_coco

_CARD = """# Synthetic document layout dataset

Generated by synthetic-pdf-bench. Labels come from the scene graph the PDFs were rendered from, not from a parser.

Each split folder has page images and `metadata.jsonl`. An `objects` field per image holds parallel lists:
`bbox` (`[x, y, width, height]` in pixels, COCO style), `category` (index into the class list below) and
`reading_order` (rank within the page).

Classes: {classes}
"""


def _split_ids(root: Path) -> dict[str, set[str] | None]:
    splits_file = root / "splits.json"
    if not splits_file.exists():
        return {"train": None}
    return {name: set(ids) for name, ids in json.loads(splits_file.read_text(encoding="utf-8"))["splits"].items() if ids}


def _pages(root: Path, doc_ids: set[str] | None):
    """Yield (image path, unique image name, annotations) per page of the given documents."""
    coco = export_coco(root, doc_ids)
    by_image: dict[int, list[dict]] = {}
    for ann in coco["annotations"]:
        by_image.setdefault(ann["image_id"], []).append(ann)
    for image in coco["images"]:
        name = f"{image['doc_id']}_p{image['page_index'] + 1:03d}.png"
        yield root / image["file_name"], name, image, by_image.get(image["id"], [])


def write_yolo(root: Path, output: Path) -> Path:
    for split, doc_ids in _split_ids(root).items():
        (output / "images" / split).mkdir(parents=True, exist_ok=True)
        (output / "labels" / split).mkdir(parents=True, exist_ok=True)
        for source, name, image, anns in _pages(root, doc_ids):
            shutil.copyfile(source, output / "images" / split / name)
            w, h = image["width"], image["height"]
            lines = [
                f"{a['category_id'] - 1} {(x + bw / 2) / w:.6f} {(y + bh / 2) / h:.6f} {bw / w:.6f} {bh / h:.6f}"
                for a in anns
                for x, y, bw, bh in [a["bbox"]]
            ]
            (output / "labels" / split / name).with_suffix(".txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    splits = _split_ids(root)
    yaml = [f"path: {output.resolve()}", *(f"{s}: images/{s}" for s in splits), "names:"]
    yaml += [f"  {i}: {name}" for i, name in enumerate(CATEGORIES)]
    (output / "data.yaml").write_text("\n".join(yaml) + "\n", encoding="utf-8")
    return output


def write_hf_imagefolder(root: Path, output: Path) -> Path:
    for split, doc_ids in _split_ids(root).items():
        (output / split).mkdir(parents=True, exist_ok=True)
        rows = []
        for source, name, _image, anns in _pages(root, doc_ids):
            shutil.copyfile(source, output / split / name)
            rows.append(
                {
                    "file_name": name,
                    "objects": {
                        "bbox": [a["bbox"] for a in anns],
                        "category": [a["category_id"] - 1 for a in anns],
                        "reading_order": [a["reading_order"] for a in anns],
                    },
                }
            )
        (output / split / "metadata.jsonl").write_text("\n".join(json.dumps(r) for r in rows) + "\n", encoding="utf-8")
    (output / "README.md").write_text(_CARD.format(classes=", ".join(f"{i}={c}" for i, c in enumerate(CATEGORIES))), encoding="utf-8")
    return output
